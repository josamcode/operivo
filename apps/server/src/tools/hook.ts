import fs from 'fs-extra';
import { join } from 'node:path';
import { config } from '../config';

/**
 * Claude Code PreToolUse hook → Opervio policy endpoint. Written at startup so paths are correct.
 * Fails closed: if Opervio cannot be reached, the tool call is blocked.
 */
const HOOK_SCRIPT = `// Generated by Opervio. PreToolUse policy hook.
const chunks = [];
for await (const c of process.stdin) chunks.push(c);
let input = {};
try { input = JSON.parse(Buffer.concat(chunks).toString() || '{}'); } catch {}
const url = process.env.OPERVIO_POLICY_URL;
if (!url) process.exit(0);
const deny = (reason) => {
  process.stdout.write(JSON.stringify({ hookSpecificOutput: { hookEventName: 'PreToolUse', permissionDecision: 'deny', permissionDecisionReason: reason } }));
  process.exit(0);
};
try {
  const res = await fetch(url, {
    method: 'POST',
    headers: { 'content-type': 'application/json' },
    body: JSON.stringify({ tool: input.tool_name, input: input.tool_input ?? {} }),
    signal: AbortSignal.timeout(15000),
  });
  const d = await res.json();
  if (d.action === 'allow') process.exit(0);
  deny(d.reason || 'Blocked by Opervio policy');
} catch {
  deny('Opervio policy service unavailable; tool use blocked.');
}
`;

export const hookPaths = () => ({
  script: join(config.paths.runtime, 'hooks', 'pretool.mjs'),
  settings: join(config.paths.runtime, 'hooks', 'settings.json'),
});

export async function installHooks() {
  const { script, settings } = hookPaths();
  await fs.ensureDir(join(config.paths.runtime, 'hooks'));
  await fs.writeFile(script, HOOK_SCRIPT);
  const command = `"${process.execPath}" "${script}"`;
  await fs.writeJson(
    settings,
    {
      hooks: {
        PreToolUse: [
          {
            matcher: 'Bash|PowerShell|Read|Write|Edit|MultiEdit|NotebookEdit|Grep|Glob',
            hooks: [{ type: 'command', command, timeout: 30 }],
          },
        ],
      },
    },
    { spaces: 2 },
  );
}
